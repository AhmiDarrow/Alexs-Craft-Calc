export const KOH_FACTOR = 1.4027

export function getOil(id: string): Oil | undefined {
  return OILS.find((o) => o.id === id)
}

export function oilsByCategory(): Record<Oil['category'], Oil[]> {
  const map: Record<Oil['category'], Oil[]> = {
    hard: [],
    soft: [],
    butter: [],
    specialty: [],
    liquid: [],
  }
  for (const o of OILS) map[o.category].push(o)
  return map
}
